package it.grypho.scala.leonardo
package mcp

import core.*
import parser.Parser

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path}
import scala.util.Try


/** The corpus of [[ToScala]]'s round-trip test (F_0126 Decision D), and the writer of the test source
 *  that compiles it.  The build runs `main` before compiling the `mcp` tests: every syntax cell of the
 *  cheat sheet is parsed, in each mode, and evaluated, each result rendered, and the renderings written
 *  into a test source — so the compiler itself checks that every rendering is valid Scala, and the test
 *  that it equals the original.  Nothing embeds a compiler. */
private[mcp] object ScalaRoundTrip:

  /** One case: the line, the mode, whether it is the evaluated result, and the value. */
  final case class Case(line: String, exact: Boolean, evaluated: Boolean, value: _Expression)

  /** The working precision an exact case is parsed at. */
  val ExactDigits = 30

  /** The lines in the first column of the cheat sheet's tables, each a single code span. */
  def syntaxCells(sheet: String): Vector[String] =
    val Cell = """^\|\s*`([^`]+)`\s*\|.*""".r
    sheet.linesIterator.collect { case Cell(code) => code.trim }.filter(_.nonEmpty).toVector.distinct

  /** The value a case denotes, recomputed. */
  def valueOf(line: String, exact: Boolean, evaluated: Boolean): Option[_Expression] =
    val parsed = Parser.parse(line, Option.when(exact)(ExactDigits))
    Option.when(parsed.successful)(parsed.get).flatMap { e =>
      if evaluated then Try(e.eval(Environment()).toExpression).toOption else Some(e)
    }

  /** Every case of the corpus. */
  def cases(sheet: String): Vector[Case] =
    for
      line      <- syntaxCells(sheet)
      exact     <- Vector(false, true)
      evaluated <- Vector(false, true)
      value     <- valueOf(line, exact, evaluated).toVector
    yield Case(line, exact, evaluated, value)

  /** Writes the test source: `args(0)` the cheat sheet, `args(1)` the output file.
   *  @param args the two paths */
  def main(args: Array[String]): Unit =
    val sheet = Files.readString(Path.of(args(0)), UTF_8)
    val all = cases(sheet)
    val rendered = all.map(c => c -> ToScala(c.value))
    // NaN is not equal to itself, so a case holding one cannot be compared and is left out
    val usable = rendered.collect { case (c, Right(src)) if !src.contains("NaN") => (c, src) }
    val declined = rendered.collect { case (c, Left(why)) => s"${c.line} -> $why" }
    def lit(s: String) = ToScala(s).getOrElse("\"\"")
    val parts = usable.grouped(40).zipWithIndex.map { (group, i) =>
      val items = group.map((c, src) => s"    (${lit(c.line)}, ${c.exact}, ${c.evaluated}, $src)").mkString(",\n")
      s"  private def part$i: Vector[(String, Boolean, Boolean, Any)] = Vector(\n$items)"
    }.toVector
    val source =
      s"""|// GENERATED by mcp.ScalaRoundTrip from docs/src/cheatsheet.md -- do not edit.
          |package it.grypho.scala.leonardo
          |package mcp
          |
          |object GeneratedRoundTrip:
          |  val total: Int = ${all.size}
          |  val declined: Vector[String] = Vector(${declined.map(lit).mkString(", ")})
          |${parts.mkString("\n")}
          |  val cases: Vector[(String, Boolean, Boolean, Any)] = ${if parts.isEmpty then "Vector.empty" else parts.indices.map(i => s"part$i").mkString(" ++ ")}
          |""".stripMargin
    Files.createDirectories(Path.of(args(1)).getParent)
    Files.writeString(Path.of(args(1)), source, UTF_8)
